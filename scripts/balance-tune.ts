/**
 * Runs the balance harness and writes docs/update-1.6.0/BALANCE_REPORT.md.
 * Usage (from the main checkout, which has vite-node):
 *   npx vite-node "<worktree>/scripts/balance-tune.ts" [--quick]
 * or `npm run balance:tune` where vite-node resolves.
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bandsMarkdown, evaluateBands, runMatrix, type PacingId } from '../src/game/sim/balance';

const here = dirname(fileURLToPath(import.meta.url));
const quick = process.argv.includes('--quick');
const seeds = quick ? [1, 2] : Array.from({ length: 20 }, (_, i) => i + 1);
const days = quick ? 30 : 60;
const started = Date.now();
const sections: string[] = [];
for (const pacing of ['medium', 'easy', 'hard'] as PacingId[]) {
  const runs = runMatrix({ pacings: [pacing], seeds: pacing === 'medium' ? seeds : seeds.slice(0, Math.max(2, seeds.length / 4)), days });
  sections.push(bandsMarkdown(evaluateBands(runs, pacing), `## ${pacing[0]!.toUpperCase()}${pacing.slice(1)} pacing (${runs.length} runs, ${days} days × 100 cards)`));
  const m = (f: (r: (typeof runs)[number]) => number) => (runs.reduce((a, r) => a + f(r), 0) / runs.length).toFixed(0);
  sections.push(`Per run: ${m((r) => r.encounters)} encounters, ${m((r) => r.final.totalCurrencyEarned ?? 0)} ₽ earned, party avg L${m((r) => r.days[r.days.length - 1]!.partyAvg)} at the end.\n`);
}
const report = [
  '# Balance report',
  '',
  `Generated by \`scripts/balance-tune.ts\`${quick ? ' (quick run)' : ''} in ${((Date.now() - started) / 1000).toFixed(0)} s. Bands are SPEC Part C2.`,
  '',
  ...sections
].join('\n');
writeFileSync(resolve(here, '../docs/update-1.6.0/BALANCE_REPORT.md'), report);
console.log(report);
