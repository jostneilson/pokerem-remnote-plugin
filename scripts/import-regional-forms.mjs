#!/usr/bin/env node
/**
 * Generates src/game/data/regionalForms.ts from the PokéAPI REST API (same database as the
 * pinned CSV import). Forms keep PokéAPI's form ids (for example 10169 for Galarian Articuno) as
 * their PokéRem dex number, so sprites resolve to the official artwork, shiny included.
 *
 * Usage: node scripts/import-regional-forms.mjs
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const FORMS = [
  { id: 10169, nationalDex: 144, name: 'Galarian Articuno' },
  { id: 10170, nationalDex: 145, name: 'Galarian Zapdos' },
  { id: 10171, nationalDex: 146, name: 'Galarian Moltres' },
];
const VERSION_GROUPS = ['scarlet-violet', 'sword-shield'];

const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const moveId = (s) => s.replace(/-/g, '');

async function json(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.json();
}

const species = [];
const learnsets = {};
const sources = {};
for (const form of FORMS) {
  const p = await json(`https://pokeapi.co/api/v2/pokemon/${form.id}`);
  const sp = await json(p.species.url);
  const stat = (n) => p.stats.find((s) => s.stat.name === n).base_stat;
  species.push({
    dexNum: form.id,
    nationalDex: form.nationalDex,
    name: form.name,
    types: p.types.sort((a, b) => a.slot - b.slot).map((t) => cap(t.type.name)),
    baseHp: stat('hp'),
    baseAttack: stat('attack'),
    baseDefense: stat('defense'),
    baseSpecialAttack: stat('special-attack'),
    baseSpecialDefense: stat('special-defense'),
    baseSpeed: stat('speed'),
    baseCatchRate: sp.capture_rate,
    tier: 'Legendary',
    classification: sp.is_mythical ? 'mythical' : sp.is_legendary ? 'legendary' : 'ordinary',
    generation: 8,
  });
  const byGroup = {};
  for (const m of p.moves) {
    for (const d of m.version_group_details) {
      if (d.move_learn_method.name !== 'level-up') continue;
      (byGroup[d.version_group.name] ??= []).push({ level: d.level_learned_at, moveId: moveId(m.move.name) });
    }
  }
  const group = VERSION_GROUPS.find((g) => byGroup[g]?.length);
  if (!group) throw new Error(`no level-up learnset for ${form.name}`);
  learnsets[form.id] = byGroup[group].sort((a, b) => a.level - b.level || a.moveId.localeCompare(b.moveId));
  sources[form.id] = group;
}

const out = `// GENERATED by scripts/import-regional-forms.mjs from the PokéAPI REST API. Do not hand edit.
import type { FullSpeciesData } from './pokedex';
import type { PokemonType } from './species';
import type { LearnsetEntry } from './learnsetRules';

export interface RegionalFormData extends FullSpeciesData {
  /** National Pokédex number of the base species, shown in the Dex. */
  nationalDex: number;
}

export const REGIONAL_FORMS: RegionalFormData[] = [
${species.map((s) => `  ${JSON.stringify(s).replace(/"types":(\[[^\]]*\])/, '"types":$1 as PokemonType[]')},`).join('\n')}
];

export const REGIONAL_FORM_LEARNSET_SOURCE: Record<number, string> = ${JSON.stringify(sources)};

export const REGIONAL_FORM_LEARNSETS: Record<number, LearnsetEntry[]> = {
${Object.entries(learnsets).map(([id, l]) => `  ${id}: ${JSON.stringify(l)},`).join('\n')}
};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'game', 'data', 'regionalForms.ts');
writeFileSync(target, out);
console.log(`wrote ${target}: ${species.map((s) => s.name).join(', ')}`);
