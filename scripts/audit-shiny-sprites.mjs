#!/usr/bin/env node
/**
 * Shiny artwork audit. Checks that every PokéRem species has an official shiny front and back
 * sprite in the PokéAPI sprite set the game already uses (same style as the normal sprites),
 * then writes src/game/data/shinyArt.ts with any gaps:
 *   - no shiny front: that species can't roll shiny, so no placeholder art ever appears;
 *   - no shiny back: the battle view mirrors the official shiny front instead.
 *
 * Usage: node scripts/audit-shiny-sprites.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const BASE = 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon';

const dexNums = new Set();
for (const file of ['src/game/data/pokedex.ts', 'src/game/data/regionalForms.ts']) {
  for (const m of readFileSync(join(root, file), 'utf8').matchAll(/"?dexNum"?:\s*(\d+)/g)) dexNums.add(Number(m[1]));
}
const ids = [...dexNums].sort((a, b) => a - b);

async function exists(url) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(url, { method: 'HEAD' });
      if (res.status === 200) return true;
      if (res.status === 404) return false;
    } catch {
      /* retry */
    }
    await new Promise((r) => setTimeout(r, 400 * (attempt + 1)));
  }
  throw new Error(`could not check ${url}`);
}

const missingFront = [];
const missingBack = [];
let next = 0;
async function worker() {
  while (next < ids.length) {
    const id = ids[next++];
    const [front, back] = await Promise.all([exists(`${BASE}/shiny/${id}.png`), exists(`${BASE}/back/shiny/${id}.png`)]);
    if (!front) missingFront.push(id);
    if (!back) missingBack.push(id);
  }
}
await Promise.all(Array.from({ length: 16 }, worker));
missingFront.sort((a, b) => a - b);
missingBack.sort((a, b) => a - b);

const out = `// GENERATED by scripts/audit-shiny-sprites.mjs (${ids.length} species checked). Do not hand edit.
// Shiny sprites are the official PokéAPI artwork, the same set and style as normal sprites.

/** Species with no official shiny front sprite. They never roll shiny. */
export const NO_SHINY_FRONT: ReadonlySet<number> = new Set(${JSON.stringify(missingFront)});

/** Species with no official shiny back sprite. Battles mirror the shiny front instead. */
export const NO_SHINY_BACK: ReadonlySet<number> = new Set(${JSON.stringify(missingBack)});

export function canBeShiny(dexNum: number): boolean {
  return !NO_SHINY_FRONT.has(dexNum);
}
`;
writeFileSync(join(root, 'src/game/data/shinyArt.ts'), out);
console.log(`checked ${ids.length}; no shiny front: ${missingFront.length} ${JSON.stringify(missingFront)}; no shiny back: ${missingBack.length} ${JSON.stringify(missingBack)}`);
